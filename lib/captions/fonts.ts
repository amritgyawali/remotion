/**
 * The caption typography kit.
 *
 * Every family here is bundled under public/assets/fonts/v1 by
 * `npm run assets:fonts`, so a caption looks identical in the preview, in a
 * browser export and on a render host - no font is fetched from the network
 * while frames are being drawn, and a missing family can never silently fall
 * back to Arial mid-render.
 *
 * The table is deliberately large. "Which font" is the loudest styling decision
 * in a subtitle, and a studio that offers six of them quietly decides how every
 * video looks. Faces are grouped by the job they do rather than by foundry:
 * text faces that stay readable at 40 lines of dialogue, condensed faces for
 * dense vertical frames, display and comic faces for hooks, retro and pixel
 * faces for gaming and glitch edits, script faces for lifestyle, and a full
 * shelf of Devanagari for Nepali and Hindi.
 *
 * `variable` matters at render time: a static face has exactly one weight, and
 * asking a browser for 700 on a 400-only file produces a synthesised fake bold
 * that smears at caption size. The studio pins the weight for those faces
 * instead of letting the slider lie.
 */

export type CaptionFontCategory =
	| 'sans'
	| 'grotesk'
	| 'rounded'
	| 'condensed'
	| 'display'
	| 'comic'
	| 'serif'
	| 'tech'
	| 'retro'
	| 'pixel'
	| 'mono'
	| 'handwriting'
	| 'script'
	| 'devanagari'

export type CaptionFontFace = {
	family: string
	/** path under public/assets/fonts/v1 */
	file: string
	/** the CSS weight or weight range the file actually carries */
	weight: string
	variable: boolean
	/** where the weight slider lands when this face is chosen */
	defaultWeight: number
	category: CaptionFontCategory
	/** true when the face itself draws Devanagari, not just Latin */
	devanagari: boolean
	fallback: string
	label: string
	mood: string
	useFor: string
}

