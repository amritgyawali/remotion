export type CaptionFontId = keyof typeof CAPTION_FACES

/** The subset that can draw Devanagari - the companion face for Nepali. */
export type CaptionDevanagariFontId = {
	[Id in CaptionFontId]: (typeof CAPTION_FACES)[Id]['devanagari'] extends true ? Id : never
}[CaptionFontId]

export const CAPTION_FONTS: Record<CaptionFontId, CaptionFontFace> = CAPTION_FACES

export const CAPTION_FONT_IDS = Object.keys(CAPTION_FACES) as CaptionFontId[]

export const DEVANAGARI_FONT_IDS = CAPTION_FONT_IDS.filter(
	(id): id is CaptionDevanagariFontId => CAPTION_FACES[id].devanagari,
)

export const DEVANAGARI_FONTS = Object.fromEntries(
	DEVANAGARI_FONT_IDS.map((id) => [id, CAPTION_FACES[id]]),
) as Record<CaptionDevanagariFontId, CaptionFontFace>

export function isCaptionFontId(value: unknown): value is CaptionFontId {
	return typeof value === 'string' && value in CAPTION_FACES
}

export function fontById(id: string): CaptionFontFace {
	return isCaptionFontId(id) ? CAPTION_FACES[id] : CAPTION_FACES.inter
}

/**
 * A static face has one weight; letting the user ask for another only produces
 * a synthesised bold or a thin that the render host draws differently from the
 * preview. Variable faces are clamped to the range the file declares.
 */
export function resolveFontWeight(id: CaptionFontId, requested: number): number {
	const face = CAPTION_FACES[id]
	const range = face.weight.split(' ').map(Number)
	if (range.length === 1) return range[0]
	const [min, max] = range
	return Math.min(max, Math.max(min, Math.round(requested / 100) * 100))
}

